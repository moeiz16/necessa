"use client";

/**
 * Clinical-AI transparency primitives. Rules they encode:
 *  - Anything a model produced is labelled as AI-suggested, with confidence and a "Why?" affordance.
 *  - Status is never conveyed by color alone (icon + text, always).
 *  - Identifiers stay masked until a permitted user reveals them; reveals are audited.
 *  - Humans decide: review state is visible wherever a verdict is shown.
 */
import { CircleCheck, CircleDashed, Eye, EyeOff, HelpCircle, Info, Lock, ShieldCheck, Sparkles, TriangleAlert, UserCheck, UserPen } from "lucide-react";
import * as React from "react";
import { cn } from "@/lib/utils";
import { Badge } from "@/components/ui/display";
import { Popover, PopoverContent, PopoverTrigger, Tooltip } from "@/components/ui/overlays";

type Tone = "neutral" | "brand" | "met" | "notmet" | "insufficient" | "degraded" | "info";

const TONE_TEXT: Record<Tone, string> = {
  neutral: "text-muted",
  brand: "text-brand-fg",
  met: "text-met-fg",
  notmet: "text-notmet-fg",
  insufficient: "text-insufficient-fg",
  degraded: "text-degraded-fg",
  info: "text-info",
};
const TONE_ICON: Record<Tone, React.ComponentType<{ className?: string }>> = {
  neutral: CircleDashed,
  brand: Info,
  met: CircleCheck,
  notmet: TriangleAlert,
  insufficient: TriangleAlert,
  degraded: CircleDashed,
  info: Info,
};

/** Icon + label status (never color alone). */
export function StatusLabel({ tone = "neutral", icon, children, className }: { tone?: Tone; icon?: React.ReactNode; children: React.ReactNode; className?: string }) {
  const Icon = TONE_ICON[tone];
  return (
    <span className={cn("inline-flex items-center gap-1.5 text-[13px] font-medium", TONE_TEXT[tone], className)}>
      <span className="shrink-0 [&_svg]:size-3.5">{icon ?? <Icon />}</span>
      <span>{children}</span>
    </span>
  );
}

/** Marks model-generated content. Hover explains what that means. */
export function AiBadge({ label = "AI-suggested", className, size = "xs", detail }: { label?: string; className?: string; size?: "xs" | "sm"; detail?: React.ReactNode }) {
  return (
    <Tooltip content={detail ?? "Generated by a model and verified against quoted sources. A person reviews it before anything is submitted."}>
      <Badge tone="ai" size={size} className={cn("cursor-default gap-1", className)}>
        <Sparkles className="!text-ai-2" />
        {label}
      </Badge>
    </Tooltip>
  );
}

/** Live "the model is working" indicator with a calm shimmer. */
export function AiWorking({ label = "Analyzing", className }: { label?: React.ReactNode; className?: string }) {
  return (
    <span role="status" aria-live="polite" className={cn("inline-flex items-center gap-1.5 text-[13px] font-medium", className)}>
      <span className="relative flex size-3.5 items-center justify-center">
        <span className="absolute inset-0 animate-[spin_2.4s_linear_infinite] rounded-full border-[1.5px] border-ai-2/25 border-t-ai-2" />
      </span>
      <span className="ai-text-shimmer">{label}</span>
    </span>
  );
}

/** A surface that shimmers while AI content streams in (wraps a card or row). */
export function AiShimmer({ active, children, className }: { active: boolean; children: React.ReactNode; className?: string }) {
  return (
    <div className={cn("relative", className)}>
      {children}
      {active ? <span aria-hidden className="ai-sheen pointer-events-none absolute inset-0 rounded-[inherit]" /> : null}
    </div>
  );
}

function confidenceBand(v: number) {
  if (v >= 0.8) return { label: "High", tone: "met" as const };
  if (v >= 0.55) return { label: "Moderate", tone: "insufficient" as const };
  return { label: "Low", tone: "notmet" as const };
}

/** Confidence as words + number (calibrated), not just bars. */
export function ConfidencePill({ value, className, showNumber = true }: { value: number; className?: string; showNumber?: boolean }) {
  const pct = Math.round(Math.max(0, Math.min(1, value)) * 100);
  const band = confidenceBand(value);
  return (
    <Tooltip content={`Model confidence ${pct}%, calibrated on the verdict evaluation set. Low confidence triggers a second retrieval pass and reviewer attention.`}>
      <span className={cn("inline-flex h-5 items-center gap-1.5 rounded-[5px] bg-surface-2 px-1.5 text-[11.5px] text-muted ring-1 ring-inset ring-border", className)}>
        <span className="flex items-end gap-[2px]" aria-hidden>
          {[0, 1, 2].map((i) => (
            <span
              key={i}
              className={cn("w-[3px] rounded-[1px]", i < (band.label === "High" ? 3 : band.label === "Moderate" ? 2 : 1) ? "bg-fg/70" : "bg-surface-3")}
              style={{ height: 5 + i * 2.5 }}
            />
          ))}
        </span>
        <span className="font-medium text-fg">{band.label}</span>
        {showNumber ? <span className="tabular">{pct}%</span> : null}
      </span>
    </Tooltip>
  );
}

