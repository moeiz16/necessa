/** Human-in-the-loop state for any AI output. */
export function ReviewBadge({ state, by, className }: { state: "pending" | "reviewed" | "overridden"; by?: string | null; className?: string }) {
  const meta = {
    pending: { icon: UserPen, label: "Awaiting human review", tone: "insufficient" as const },
    reviewed: { icon: UserCheck, label: by ? `Reviewed by ${by}` : "Human-reviewed", tone: "met" as const },
    overridden: { icon: UserPen, label: by ? `Overridden by ${by}` : "Overridden by reviewer", tone: "brand" as const },
  }[state];
  const Icon = meta.icon;
  return (
    <Badge tone={meta.tone} size="xs" className={className}>
      <Icon />
      {meta.label}
    </Badge>
  );
}

/**
 * Masked identifier with an explicit, audited reveal.
 * `onReveal` should call the API with `reveal=true`; the component shows the returned value.
 */
export function PhiMask({
  masked,
  value,
  onReveal,
  canReveal = true,
  label = "identifier",
  className,
}: {
  masked: React.ReactNode;
  value?: React.ReactNode | null;
  onReveal?: () => void | Promise<void>;
  canReveal?: boolean;
  label?: string;
  className?: string;
}) {
  const [busy, setBusy] = React.useState(false);
  const [hidden, setHidden] = React.useState(false);
  const shown = value != null && !hidden;
  return (
    <span className={cn("inline-flex items-center gap-1.5", className)}>
      <span className={cn("tabular", shown ? "text-fg" : "font-mono text-muted")}>{shown ? value : masked}</span>
      {shown ? (
        <Tooltip content="Hide again">
          <button type="button" onClick={() => setHidden(true)} className="rounded p-0.5 text-subtle hover:bg-surface-2 hover:text-fg" aria-label={`Hide ${label}`}>
            <EyeOff className="size-3.5" />
          </button>
        </Tooltip>
      ) : canReveal && onReveal ? (
        <Tooltip content="Reveal — this access is recorded in the audit log">
          <button
            type="button"
            disabled={busy}
            onClick={async () => {
              setHidden(false);
              if (value != null) return;
              setBusy(true);
              try {
                await onReveal();
              } finally {
                setBusy(false);
              }
            }}
            className="inline-flex items-center gap-1 rounded px-1 text-[11px] font-medium text-brand-fg hover:bg-brand-soft disabled:opacity-50"
            aria-label={`Reveal ${label} (audited)`}
          >
            <Eye className="size-3.5" />
            Reveal
          </button>
        </Tooltip>
      ) : (
        <Tooltip content="You don't have permission to reveal patient identifiers">
          <Lock className="size-3.5 text-subtle" aria-label="Masked" />
        </Tooltip>
      )}
    </span>
  );
}

/** One-line source provenance for quoted evidence. */
export function Provenance({ source, detail, verified = true, className }: { source: React.ReactNode; detail?: React.ReactNode; verified?: boolean; className?: string }) {
  return (
    <p className={cn("flex flex-wrap items-center gap-x-1.5 gap-y-0.5 text-[11.5px] text-subtle", className)}>
      <span className="text-muted">{source}</span>
      {detail ? <span>· {detail}</span> : null}
      {verified ? (
        <span className="inline-flex items-center gap-1 text-met-fg">
          · <ShieldCheck className="size-3" /> verified verbatim
        </span>
      ) : (
        <span className="inline-flex items-center gap-1 text-insufficient-fg">
          · <TriangleAlert className="size-3" /> not verified
        </span>
      )}
    </p>
  );
}

